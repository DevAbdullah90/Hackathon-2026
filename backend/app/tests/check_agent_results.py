"""
app/tests/check_agent_results.py
───────────────────────────────
Checks the database for Incidents and Reasoning Logs generated by the AI.
Usage: python -m app.tests.check_agent_results
"""

import os
import asyncio
from sqlalchemy.ext.asyncio import create_async_engine
from sqlalchemy import text
from dotenv import load_dotenv

load_dotenv()

DATABASE_URL = os.getenv("DATABASE_URL")

async def check_results():
    # Clean the URL for asyncpg
    clean_url = DATABASE_URL.split('?')[0]
    engine = create_async_engine(clean_url, connect_args={"ssl": True}, echo=False)
    
    try:
        async with engine.connect() as conn:
            # 1. Check Incidents
            print("\n--- INCIDENTS DETECTED BY AI ---")
            result = await conn.execute(text("SELECT id, location, severity_score, status FROM incidents"))
            incidents = result.all()
            if not incidents:
                print("No incidents found yet. (Wait a few seconds for the background task)")
            for inc in incidents:
                print(f"ID: {inc.id} | Location: {inc.location} | Severity: {inc.severity_score} | Status: {inc.status}")

            # 2. Check Reasoning Logs
            print("\n--- AI REASONING LOGS ---")
            result = await conn.execute(text("SELECT agent_name, log_level, log_text FROM reasoning_logs LIMIT 5"))
            logs = result.all()
            if not logs:
                print("No reasoning logs found yet.")
            for log in logs:
                print(f"Agent: {log.agent_name} | Level: {log.log_level}")
                print(f"Content Summary: {log.log_text[:100]}...")
                print("-" * 20)
            
    except Exception as e:
        print(f"Error: {e}")
    finally:
        await engine.dispose()

if __name__ == "__main__":
    asyncio.run(check_results())
